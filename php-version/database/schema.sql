-- CampusOS Core PHP / MySQL schema. MySQL 8.0+, utf8mb4. No test users or credentials.
SET NAMES utf8mb4;
CREATE TABLE IF NOT EXISTS vendor_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS schools (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(190) NOT NULL,
 code VARCHAR(64) NOT NULL UNIQUE, delivery_model ENUM('saas','direct') NOT NULL DEFAULT 'saas',
 status ENUM('active','suspended') NOT NULL DEFAULT 'active',
 phone VARCHAR(48) DEFAULT NULL, email VARCHAR(190) DEFAULT NULL,
 address TEXT DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS branches (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(190) NOT NULL, code VARCHAR(32) NOT NULL, city VARCHAR(100) DEFAULT NULL,
 address TEXT DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_branch (school_id,code), FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED DEFAULT NULL,
 role ENUM('admin','principal','accountant','teacher','student','parent','staff') NOT NULL,
 full_name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL,
 password_hash VARCHAR(255) NOT NULL, status ENUM('active','inactive') NOT NULL DEFAULT 'active',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_school_email (school_id,email),
 INDEX idx_school_role (school_id,role),
 FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subscriptions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 plan_name VARCHAR(100) NOT NULL, status ENUM('trial','active','past_due','cancelled') NOT NULL DEFAULT 'trial',
 starts_on DATE DEFAULT NULL, ends_on DATE DEFAULT NULL, amount DECIMAL(12,2) NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS licenses (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 license_ref VARCHAR(96) NOT NULL UNIQUE, status ENUM('active','expired','revoked') NOT NULL DEFAULT 'active',
 expires_on DATE DEFAULT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS school_sessions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(60) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 is_current TINYINT(1) NOT NULL DEFAULT 0,
 UNIQUE KEY unique_year (school_id,name), FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS classes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(80) NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 UNIQUE KEY unique_class (school_id,name), FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sections (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, class_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(32) NOT NULL, capacity INT UNSIGNED NOT NULL DEFAULT 40,
 UNIQUE KEY unique_section (school_id,branch_id,class_id,name),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id), FOREIGN KEY(class_id) REFERENCES classes(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS subjects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, code VARCHAR(32) NOT NULL,
 UNIQUE KEY unique_subject (school_id,code),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS student_profiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NOT NULL,
 parent_user_id BIGINT UNSIGNED DEFAULT NULL, class_id BIGINT UNSIGNED NOT NULL,
 section_id BIGINT UNSIGNED NOT NULL, admission_no VARCHAR(64) NOT NULL,
 roll_no VARCHAR(64) DEFAULT NULL, birth_date DATE DEFAULT NULL,
 UNIQUE KEY unique_student_account (school_id,user_id),
 UNIQUE KEY unique_admission (school_id,admission_no),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(user_id) REFERENCES users(id), FOREIGN KEY(parent_user_id) REFERENCES users(id),
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(section_id) REFERENCES sections(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS teacher_allocations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, teacher_user_id BIGINT UNSIGNED NOT NULL,
 class_id BIGINT UNSIGNED NOT NULL, section_id BIGINT UNSIGNED NOT NULL, subject_id BIGINT UNSIGNED NOT NULL,
 UNIQUE KEY unique_allocation (school_id,teacher_user_id,class_id,section_id,subject_id),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(teacher_user_id) REFERENCES users(id),
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(section_id) REFERENCES sections(id),
 FOREIGN KEY(subject_id) REFERENCES subjects(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS timetable (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, class_id BIGINT UNSIGNED NOT NULL,
 section_id BIGINT UNSIGNED NOT NULL, subject_id BIGINT UNSIGNED NOT NULL,
 teacher_user_id BIGINT UNSIGNED NOT NULL, weekday TINYINT UNSIGNED NOT NULL,
 period_no TINYINT UNSIGNED NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
 room VARCHAR(60) DEFAULT NULL,
 UNIQUE KEY unique_section_period (school_id,branch_id,section_id,weekday,period_no),
 UNIQUE KEY unique_teacher_period (school_id,teacher_user_id,weekday,period_no),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(section_id) REFERENCES sections(id),
 FOREIGN KEY(subject_id) REFERENCES subjects(id), FOREIGN KEY(teacher_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS attendance (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, student_user_id BIGINT UNSIGNED NOT NULL,
 class_id BIGINT UNSIGNED NOT NULL, section_id BIGINT UNSIGNED NOT NULL,
 day DATE NOT NULL, status ENUM('present','absent','late','leave') NOT NULL,
 entered_by BIGINT UNSIGNED NOT NULL, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY unique_attendance (school_id,student_user_id,day),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(student_user_id) REFERENCES users(id), FOREIGN KEY(entered_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS homework (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, class_id BIGINT UNSIGNED NOT NULL,
 section_id BIGINT UNSIGNED NOT NULL, subject_id BIGINT UNSIGNED NOT NULL,
 teacher_user_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(190) NOT NULL, instructions TEXT NOT NULL,
 due_at DATETIME NOT NULL, close_at DATETIME NOT NULL,
 max_marks DECIMAL(7,2) NOT NULL DEFAULT 10, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(section_id) REFERENCES sections(id),
 FOREIGN KEY(subject_id) REFERENCES subjects(id), FOREIGN KEY(teacher_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS homework_submissions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 homework_id BIGINT UNSIGNED NOT NULL, student_user_id BIGINT UNSIGNED NOT NULL,
 answer_text MEDIUMTEXT NOT NULL, submitted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 marks DECIMAL(7,2) DEFAULT NULL, feedback TEXT DEFAULT NULL, graded_by BIGINT UNSIGNED DEFAULT NULL,
 UNIQUE KEY unique_submission (school_id,homework_id,student_user_id),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(homework_id) REFERENCES homework(id), FOREIGN KEY(student_user_id) REFERENCES users(id),
 FOREIGN KEY(graded_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS exams (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, class_id BIGINT UNSIGNED NOT NULL,
 section_id BIGINT UNSIGNED NOT NULL, subject_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(190) NOT NULL, exam_date DATE NOT NULL,
 max_marks DECIMAL(7,2) NOT NULL DEFAULT 100, passing_marks DECIMAL(7,2) NOT NULL DEFAULT 33,
 published TINYINT(1) NOT NULL DEFAULT 0,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id),
 FOREIGN KEY(class_id) REFERENCES classes(id), FOREIGN KEY(section_id) REFERENCES sections(id),
 FOREIGN KEY(subject_id) REFERENCES subjects(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS exam_results (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 exam_id BIGINT UNSIGNED NOT NULL, student_user_id BIGINT UNSIGNED NOT NULL,
 marks DECIMAL(7,2) NOT NULL, remarks VARCHAR(255) DEFAULT NULL,
 recorded_by BIGINT UNSIGNED NOT NULL,
 UNIQUE KEY unique_exam_student (school_id,exam_id,student_user_id),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(exam_id) REFERENCES exams(id), FOREIGN KEY(student_user_id) REFERENCES users(id),
 FOREIGN KEY(recorded_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fee_invoices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, student_user_id BIGINT UNSIGNED NOT NULL,
 invoice_no VARCHAR(64) NOT NULL, description VARCHAR(190) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, due_date DATE NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_invoice (school_id,invoice_no),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(branch_id) REFERENCES branches(id), FOREIGN KEY(student_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS fee_payments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 invoice_id BIGINT UNSIGNED NOT NULL, amount DECIMAL(12,2) NOT NULL,
 mode ENUM('cash','bank','cheque','online_manual') NOT NULL,
 reference VARCHAR(100) DEFAULT NULL, received_by BIGINT UNSIGNED NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(invoice_id) REFERENCES fee_invoices(id), FOREIGN KEY(received_by) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS notices (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED DEFAULT NULL, title VARCHAR(190) NOT NULL,
 body TEXT NOT NULL, audience ENUM('all','teachers','students','parents') NOT NULL DEFAULT 'all',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS library_books (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, title VARCHAR(190) NOT NULL,
 author VARCHAR(190) DEFAULT NULL, isbn VARCHAR(40) DEFAULT NULL,
 copies INT UNSIGNED NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE, FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS transport_routes (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, name VARCHAR(190) NOT NULL,
 vehicle VARCHAR(80) DEFAULT NULL, driver_name VARCHAR(160) DEFAULT NULL,
 monthly_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE, FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS inventory_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL, name VARCHAR(190) NOT NULL,
 sku VARCHAR(64) DEFAULT NULL, quantity INT NOT NULL DEFAULT 0,
 reorder_at INT NOT NULL DEFAULT 0, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE, FOREIGN KEY(branch_id) REFERENCES branches(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS payroll_entries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 employee_user_id BIGINT UNSIGNED NOT NULL, month_key CHAR(7) NOT NULL,
 basic DECIMAL(12,2) NOT NULL DEFAULT 0, allowance DECIMAL(12,2) NOT NULL DEFAULT 0,
 deduction DECIMAL(12,2) NOT NULL DEFAULT 0, status ENUM('unpaid','paid') NOT NULL DEFAULT 'unpaid',
 UNIQUE KEY unique_payroll (school_id,employee_user_id,month_key),
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(employee_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS certificates (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 student_user_id BIGINT UNSIGNED NOT NULL, title VARCHAR(190) NOT NULL,
 body TEXT NOT NULL, issued_on DATE NOT NULL,
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(student_user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS leave_requests (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 reason TEXT NOT NULL, status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 FOREIGN KEY(school_id) REFERENCES schools(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, school_id BIGINT UNSIGNED DEFAULT NULL,
 user_id BIGINT UNSIGNED DEFAULT NULL, event VARCHAR(80) NOT NULL,
 entity VARCHAR(80) NOT NULL, entity_id BIGINT UNSIGNED DEFAULT NULL,
 ip_address VARCHAR(45) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_school (school_id,created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, identifier VARCHAR(190) NOT NULL,
 ip_address VARCHAR(45) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_throttle (identifier,ip_address,created_at)
) ENGINE=InnoDB;
